import type { FileEntry } from "@cortex/gateway-contract";

export const indexMarker = "<!-- generated by cortex, do not edit -->";

export type IndexScope = "sector" | "specs" | "backlog" | "findings";

const scopePrefix: Record<Exclude<IndexScope, "sector">, string> = { specs: "specs/", backlog: "docs/backlog/", findings: "docs/findings/" };

export function indexTargets(entries: FileEntry[]): Array<{ dir: string; scope: IndexScope }> {
  const targets: Array<{ dir: string; scope: IndexScope }> = [{ dir: "", scope: "sector" }];
  for (const scope of ["specs", "backlog", "findings"] as const) {
    if (entries.some((entry) => entry.path.startsWith(scopePrefix[scope]))) targets.push({ dir: scopePrefix[scope].slice(0, -1), scope });
  }
  return targets;
}

function row(entry: FileEntry, base: string): string {
  const link = base === "" ? entry.path : entry.path.slice(base.length + 1);
  const status = entry.meta.status === null ? "" : entry.meta.status;
  const links = [entry.meta.supersedes === null ? "" : `supersedes ${entry.meta.supersedes}`, entry.meta.supersededBy === null ? "" : `superseded by ${entry.meta.supersededBy}`, entry.meta.relatesTo === null ? "" : `relates to ${entry.meta.relatesTo}`].filter((part) => part !== "").join(", ");
  return `| ${entry.meta.docId ?? ""} | [${entry.title.replace(/\|/g, "\\|")}](${link}) | ${status} | ${links} | ${entry.updatedAt.slice(0, 10)} |`;
}

export function renderIndex(sectorName: string, entries: FileEntry[], target: { dir: string; scope: IndexScope }): string {
  const scoped = target.scope === "sector" ? entries : entries.filter((entry) => entry.path.startsWith(`${target.dir}/`));
  const sorted = [...scoped].sort((a, b) => (a.meta.docId ?? "~").localeCompare(b.meta.docId ?? "~") || a.path.localeCompare(b.path));
  const title = target.scope === "sector" ? sectorName : `${sectorName} - ${target.scope}`;
  return [indexMarker, "", `# ${title}`, "", "| ID | Title | Status | Links | Updated |", "| --- | --- | --- | --- | --- |", ...sorted.map((entry) => row(entry, target.dir)), ""].join("\n");
}
